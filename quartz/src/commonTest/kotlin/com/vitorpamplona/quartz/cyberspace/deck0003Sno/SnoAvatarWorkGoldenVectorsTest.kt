/**
 * The avatar-work golden vectors from the reference implementation.
 *
 * `CYBERSPACE_V2.md` §8.10 says its two reference implementations, `avatar.ts`
 * in cyberspace-core and `cyberspace_core/avatar.py` in cyberspace-cli, are
 * "pinned to one set of golden vectors". This is that set, read out of
 * `tests/fixtures/avatar_work.json` in cyberspace-cli (MIT), so our ladder is
 * checked against the implementation the spec points at and not only against
 * the pseudocode we both read.
 *
 * Two of the fixtures need a word:
 * - **"half gibson, ticks"** is the case a careless reader gets wrong. Its
 *   vertex is `[-1, -1, -1]` with ticks `[60, 60, 60]`, which is -0.5 of a unit,
 *   not -1.5: the whole part is the floor and the ticks count up from it, so the
 *   ticks must be added to the signed whole before the magnitude is taken.
 * - **"detailed but small"** indexes faces past the end of its vertex list,
 *   because the work formula only counts faces and never looks at them. §1.9
 *   would refuse that payload, so this keeps the face count and substitutes
 *   indices the parser accepts, which is the same input as far as the formula
 *   is concerned.
 */
