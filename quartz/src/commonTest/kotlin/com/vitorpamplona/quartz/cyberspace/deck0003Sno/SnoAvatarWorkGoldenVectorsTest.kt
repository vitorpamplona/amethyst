    @Test
    fun ourLadderMatchesTheReferenceImplementation() {
        vectors.forEach { vector ->
            val payload = SnoParser.parse(vector.json).payloadOrNull()
            assertNotNull(payload, "${vector.name} did not parse")
            assertEquals(vector.required, SnoAvatarWork.required(payload), "${vector.name} (reach ${vector.reach})")
        }
    }

    @Test
    fun theWholeSetIsCovered() {
        assertEquals(8, vectors.size)
    }
