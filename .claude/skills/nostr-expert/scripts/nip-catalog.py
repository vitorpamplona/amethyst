# Regenerates references/nip-catalog.md from a Quartz checkout (github.com/vitorpamplona/quartz).
import os, re, sys
HEADER = """# Quartz package catalog

Every top-level package of [Quartz](https://github.com/vitorpamplona/quartz) and the
event classes it defines, keyed by their `const val KIND`, with the module (artifact
`quartz-<module>`) each lives in. Generated by `scripts/nip-catalog.py` from a Quartz
checkout; regenerate it after Quartz adds a package or a kind instead of editing by hand:

```bash
python3 .claude/skills/nostr-expert/scripts/nip-catalog.py ../quartz \\
  > .claude/skills/nostr-expert/references/nip-catalog.md
```

"No event kinds" means the package holds tags, crypto, codecs or client helpers only.
The same kind under two classes is real (tag-dispatched kinds such as 30301/38000) —
grep the class. `ls` of the package root stays the ground truth, and
`scripts/nip-lookup.sh <NN>` lists one package's files.
"""
# Quartz is split into modules (core/, social/, ...); a package can span several.
repo = sys.argv[1] if len(sys.argv) > 1 else '../quartz'
SUB = os.path.join('src', 'commonMain', 'kotlin', 'com', 'vitorpamplona', 'quartz')
roots = {m: os.path.join(repo, m, SUB) for m in sorted(os.listdir(repo)) if os.path.isdir(os.path.join(repo, m, SUB))}
def package_dirs(rel):
    return [(m, os.path.join(r, rel)) for m, r in roots.items() if os.path.isdir(os.path.join(r, rel))]
kre = re.compile(r'const val KIND\s*=\s*([0-9_]+)')
def scan(d):
    out = []
    for dp, dn, fn in os.walk(d):
        for f in sorted(fn):
            if not f.endswith('.kt'): continue
            t = open(os.path.join(dp, f), encoding='utf-8').read()
            for m in kre.finditer(t):
                out.append((int(m.group(1).replace('_','')), f[:-3]))
    return sorted(set(out))
def row(name):
    places = package_dirs(name)
    ev = sorted(set(e for _, p in places for e in scan(p)))
    cells = ', '.join(f'{c} {k}' for k, c in ev) if ev else '(no event kinds: tags/utilities)'
    modules = ', '.join(sorted(set(m for m, _ in places)))
    return f'| `{name}/` | {modules} | {cells} |'
dirs = sorted(set(d for r in roots.values() for d in os.listdir(r) if os.path.isdir(os.path.join(r, d))))
print(HEADER)
print('## Standard NIP packages (`nipXX*`)\n')
print('| Package | Module | Event classes (kind) |\n|---|---|---|')
for d in dirs:
    if d.startswith('nip'): print(row(d))
print('\n## Non-NIP protocol families\n')
print('| Package | Module | Event classes (kind) |\n|---|---|---|')
for d in dirs:
    if not d.startswith('nip') and d not in ('experimental','utils'):
        print(row(d))
print('\n## `experimental/` (draft / unmerged NIPs)\n')
print('| Package | Module | Event classes (kind) |\n|---|---|---|')
ex = sorted(set(d for _, p in package_dirs('experimental') for d in os.listdir(p) if os.path.isdir(os.path.join(p, d))))
for d in ex:
    print(row('experimental/' + d))
