package com.vitorpamplona.amethyst.commons.service.uploads.video

/**
 * What the platform's compressor would do with a picked video's dynamic range: [isHdr] when the
 * source is HLG or PQ, and [canKeepHdr] when compressing it as H.265 on this device keeps that HDR
 * instead of tone mapping it to SDR. Always false for an SDR source.
 */
data class VideoHdrInfo(
    val isHdr: Boolean,
    val canKeepHdr: Boolean,
)
