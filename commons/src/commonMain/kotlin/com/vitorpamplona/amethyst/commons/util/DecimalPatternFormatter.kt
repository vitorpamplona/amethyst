/**
 * Formats numbers with a `java.text.DecimalFormat` pattern ("##.00", "###") in the default
 * locale's symbols: "-1.25" in en-US, "-1,25" in de-DE. Not thread-safe; build one per caller.
 */
expect class DecimalPatternFormatter(
    pattern: String,
) {
    fun format(value: Double): String
}
